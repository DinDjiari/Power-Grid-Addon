package com.dindjiari.pghv.block.entity;

import net.minecraft.core.BlockPos;
import net.minecraft.core.HolderLookup;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockState;
import org.jetbrains.annotations.Nullable;

/** Stores only the position of the owning cable box (box A). */
public class CableSegmentBlockEntity extends BlockEntity {
    @Nullable
    private BlockPos owner;

    public CableSegmentBlockEntity(BlockEntityType<?> type, BlockPos pos, BlockState state) {
        super(type, pos, state);
    }

    @Nullable
    public BlockPos getOwner() {
        return owner;
    }

    public void setOwner(@Nullable BlockPos owner) {
        this.owner = owner == null ? null : owner.immutable();
        setChanged();
    }

    @Override
    protected void saveAdditional(CompoundTag tag, HolderLookup.Provider registries) {
        super.saveAdditional(tag, registries);
        if (owner != null)
            tag.putLong("Owner", owner.asLong());
    }

    @Override
    protected void loadAdditional(CompoundTag tag, HolderLookup.Provider registries) {
        super.loadAdditional(tag, registries);
        owner = tag.contains("Owner") ? BlockPos.of(tag.getLong("Owner")) : null;
    }
}
