package com.dindjiari.pghv.registry;

import com.dindjiari.pghv.Pghv;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.sounds.SoundEvent;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

/** Sound events of pghv; files and subtitles in assets/pghv/sounds.json, generated by tools/sounds/make_sounds.py. */
public class PghvSounds {
    public static final DeferredRegister<SoundEvent> SOUNDS = DeferredRegister.create(Registries.SOUND_EVENT, Pghv.MOD_ID);

    public static final DeferredHolder<SoundEvent, SoundEvent> WALL_SWITCH_ON = register("block.wall_switch.on");
    public static final DeferredHolder<SoundEvent, SoundEvent> WALL_SWITCH_OFF = register("block.wall_switch.off");
    public static final DeferredHolder<SoundEvent, SoundEvent> WALL_BUTTON_PRESS = register("block.wall_button.press");
    public static final DeferredHolder<SoundEvent, SoundEvent> WALL_BUTTON_RELEASE = register("block.wall_button.release");
    public static final DeferredHolder<SoundEvent, SoundEvent> BREAKER_ON = register("block.breaker.on");
    public static final DeferredHolder<SoundEvent, SoundEvent> BREAKER_OFF = register("block.breaker.off");
    public static final DeferredHolder<SoundEvent, SoundEvent> BREAKER_TRIP = register("block.breaker.trip");
    public static final DeferredHolder<SoundEvent, SoundEvent> MODULE_INSERT = register("block.distribution_board.module_insert");
    public static final DeferredHolder<SoundEvent, SoundEvent> FUSE_INSERT = register("block.distribution_board.fuse_insert");
    public static final DeferredHolder<SoundEvent, SoundEvent> FUSE_BLOW = register("block.distribution_board.fuse_blow");
    public static final DeferredHolder<SoundEvent, SoundEvent> MAIN_SWITCH_ON = register("block.house_connection_box.on");
    public static final DeferredHolder<SoundEvent, SoundEvent> MAIN_SWITCH_OFF = register("block.house_connection_box.off");
    public static final DeferredHolder<SoundEvent, SoundEvent> COOLING_FAN_RUN = register("block.cooling_fan.run");
    public static final DeferredHolder<SoundEvent, SoundEvent> COOLING_FAN_TRIP = register("block.cooling_fan.trip");

    private static DeferredHolder<SoundEvent, SoundEvent> register(String name) {
        return SOUNDS.register(name, () -> SoundEvent.createVariableRangeEvent(
                ResourceLocation.fromNamespaceAndPath(Pghv.MOD_ID, name)));
    }
}
