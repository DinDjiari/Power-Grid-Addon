package com.dindjiari.pghv.client.ponder;

import com.dindjiari.pghv.registry.PghvItems;
import net.createmod.ponder.api.registration.PonderSceneRegistrationHelper;
import net.minecraft.resources.ResourceLocation;

/**
 * Scene registration. Structures: assets/pghv/ponder/&lt;name&gt;.nbt (generated by the scratchpad tool
 * gen_ponder_nbt.py, see docs/API_ANNAHMEN.md).
 */
public class PghvPonderScenes {
    public static void register(PonderSceneRegistrationHelper<ResourceLocation> helper) {
        helper.addStoryBoard(PghvItems.COOLING_FAN.getId(), "cooling_fan",
                FanScenes::coolingFan, PghvPonderTags.HIGH_VOLTAGE);

        helper.forComponents(PghvItems.BRASS_COOLING_FAN.getId())
                .addStoryBoard("brass_cooling_fan", FanScenes::brassCoolingFan, PghvPonderTags.HIGH_VOLTAGE)
                .addStoryBoard("brass_cooling_fan", FanScenes::overheatProtection, PghvPonderTags.HIGH_VOLTAGE);

        helper.addStoryBoard(PghvItems.DATA_CABLE.getId(), "brass_cooling_fan",
                FanScenes::overheatProtection, PghvPonderTags.HIGH_VOLTAGE);

        helper.forComponents(PghvItems.CABLE_BOX.getId(), PghvItems.UNDERGROUND_CABLE.getId(), PghvItems.BARE_CABLE.getId())
                .addStoryBoard("underground_cable", CableScenes::undergroundCable, PghvPonderTags.HIGH_VOLTAGE);
    }
}
