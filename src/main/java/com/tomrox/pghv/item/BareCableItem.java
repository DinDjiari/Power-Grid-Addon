package com.tomrox.pghv.item;

import net.minecraft.ChatFormatting;
import net.minecraft.network.chat.Component;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;

import java.util.List;

/** Bare multi-core cable: crafting intermediate, cannot be placed. */
public class BareCableItem extends Item {
    public BareCableItem(Properties properties) {
        super(properties);
    }

    @Override
    public void appendHoverText(ItemStack stack, TooltipContext context, List<Component> tooltip, TooltipFlag flag) {
        super.appendHoverText(stack, context, tooltip, flag);
        CableTooltips.addCores(stack, context.registries(), tooltip);
        tooltip.add(Component.translatable("pghv.cable.tooltip.bare_hint").withStyle(ChatFormatting.DARK_GRAY));
    }
}
